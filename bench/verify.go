// runVerifyOffline is `bench verify-offline`: it reads the outputs of the offline tier
// (scripts/repro-offline.sh), derives every headline number and compares it with the expected
// values in bench/data/expected-offline.json. Any mismatch or missing input fails.
func runVerifyOffline(args []string) error {
	fs := flag.NewFlagSet("verify-offline", flag.ContinueOnError)
	expFile := fs.String("expected", "bench/data/expected-offline.json", "expected numbers")
	evalTest := fs.String("eval-test", "", "eval/v1 result of the TEST replay")
	evalDev := fs.String("eval-dev", "", "eval/v1 result of the DEV replay")
	ledgerRep := fs.String("ledger-replay", "", "bench ledger-replay JSON")
	replay := fs.String("replay", "", "bench replay (history replay) JSON")
	evalset := fs.String("evalset", "", "snippet eval set regenerated by bench replay -eval-out")
	muts := fs.String("mutations", "", "mutation set regenerated by bench mutate")
	if err := fs.Parse(args); err != nil {
		return fmt.Errorf("verify-offline flags: %w", err)
	}
	var want map[string]any
	b, err := os.ReadFile(*expFile)
	if err != nil {
		return fmt.Errorf("expected: %w", err)
	}
	if err := json.Unmarshal(b, &want); err != nil {
		return fmt.Errorf("expected %s: %w", *expFile, err)
	}
	got := map[string]string{}
	var errs []error
	add := func(err error) {
		if err != nil {
			errs = append(errs, err)
		}
	}
	add(observeEval(got, "agentic_test", *evalTest))
	add(observeEval(got, "agentic_dev", *evalDev))
	add(observeLedgerReplay(got, *ledgerRep, *replay))
	add(observeReplay(got, *replay))
	add(observeFile(got, "snippet_evalset", *evalset))
	add(observeMutations(got, *muts))
	if len(errs) > 0 {
		return errors.Join(errs...)
	}
	return compareObserved(want, got)
}

func compareObserved(want map[string]any, got map[string]string) error {
	keys := make([]string, 0, len(want))
	for k := range want {
		if !strings.HasPrefix(k, "_") {
			keys = append(keys, k)
		}
	}
	sort.Strings(keys)
	bad := 0
	for _, k := range keys {
		w := fmt.Sprint(want[k])
		g, ok := got[k]
		status := "ok"
		if !ok || g != w {
			status, bad = "MISMATCH", bad+1
		}
		if !ok {
			g = "(not produced)"
		}
		fmt.Printf("%-8s %-44s want %-24s got %s\n", status, k, w, g)
	}
	if bad > 0 {
		return fmt.Errorf("%d of %d expected numbers differ", bad, len(keys))
	}
	fmt.Printf("all %d expected numbers reproduced\n", len(keys))
	return nil
}

func readJSON(file string, v any) error {
	if file == "" {
		return errors.New("an input file is missing (see -h)")
	}
	b, err := os.ReadFile(file)
	if err != nil {
		return fmt.Errorf("read: %w", err)
	}
	if err := json.Unmarshal(b, v); err != nil {
		return fmt.Errorf("%s: %w", file, err)
	}
	return nil
}

// observeEval reads an eval/v1 result of an agentic replay.
func observeEval(got map[string]string, name, file string) error {
	var r struct {
		Set struct {
			SHA256 string `json:"sha256"`
		} `json:"set"`
		PromptHash string `json:"prompt_template_hash"`
		Scores     struct {
			Items    int     `json:"items"`
			Errors   int     `json:"errors"`
			TP       int     `json:"true_positives"`
			FP       int     `json:"false_positives"`
			FN       int     `json:"false_negatives"`
			TN       int     `json:"true_negatives"`
			Recall   float64 `json:"recall"`
			Prec     float64 `json:"precision"`
			Unknown  float64 `json:"unknown_rate"`
			ParseErr int     `json:"parse_failures"`
		} `json:"scores"`
		Drift []struct {
			Repo      string `json:"repo"`
			Raw       int    `json:"raw"`
			Validated int    `json:"validated"`
		} `json:"drift"`
	}
	if err := readJSON(file, &r); err != nil {
		return fmt.Errorf("%s: %w", name, err)
	}
	s := r.Scores
	got[name+".set_sha256"] = r.Set.SHA256
	got[name+".prompt_template_hash"] = r.PromptHash
	got[name+".items"] = strconv.Itoa(s.Items)
	got[name+".errors"] = strconv.Itoa(s.Errors)
	got[name+".tp_fp_fn_tn"] = fmt.Sprintf("%d/%d/%d/%d", s.TP, s.FP, s.FN, s.TN)
	got[name+".recall"] = fmt.Sprintf("%.2f", s.Recall)
	got[name+".precision"] = fmt.Sprintf("%.2f", s.Prec)
	got[name+".unknown_rate"] = fmt.Sprintf("%.2f", s.Unknown)
	got[name+".parse_failures"] = strconv.Itoa(s.ParseErr)
	for _, d := range r.Drift {
		got[name+".drift."+d.Repo] = fmt.Sprintf("%d/%d", d.Validated, d.Raw)
	}
	return nil
}

type replayJSON struct {
	Repos []struct {
		Repo  string `json:"repo"`
		Split string `json:"split"`
		Items []struct {
			File   string `json:"file"`
			Line   int    `json:"line"`
			Status string `json:"status"`
			First  bool   `json:"flagged_at_first_causing_commit"`
			Any    bool   `json:"flagged_at_any_causing_commit"`
		} `json:"items"`
	} `json:"repos"`
}

// observeLedgerReplay reads bench ledger-replay and scores the history replay (impact
// selection) on the same scored items, for the like-for-like comparison.
func observeLedgerReplay(got map[string]string, file, replayFile string) error {
	var lr ledgerReplay
	if err := readJSON(file, &lr); err != nil {
		return fmt.Errorf("ledger replay: %w", err)
	}
	var rp replayJSON
	if err := readJSON(replayFile, &rp); err != nil {
		return fmt.Errorf("history replay: %w", err)
	}
	impact := map[string][2]bool{}
	for _, r := range rp.Repos {
		for _, it := range r.Items {
			impact[fmt.Sprintf("%s|%s|%d", path.Base(r.Repo), it.File, it.Line)] = [2]bool{it.First, it.Any}
		}
	}
	var scored, first, anyc, iFirst, iAny int
	for _, rr := range lr.Repos {
		stale, zero := 0, 0
		for _, c := range rr.Commits {
			stale += c.Stale
			if c.Stale == 0 {
				zero++
			}
		}
		got["ledger_replay."+rr.Repo+".claims"] = strconv.Itoa(rr.Claims)
		got["ledger_replay."+rr.Repo+".commits"] = strconv.Itoa(len(rr.Commits))
		got["ledger_replay."+rr.Repo+".stale_total"] = strconv.Itoa(stale)
		got["ledger_replay."+rr.Repo+".commits_staling_nothing"] = strconv.Itoa(zero)
		for _, it := range rr.Items {
			if it.Status != "scored" {
				continue
			}
			scored++
			first += b2i(it.First)
			anyc += b2i(it.Any)
			im, ok := impact[fmt.Sprintf("%s|%s|%d", rr.Repo, it.Path, it.Line)]
			if !ok {
				return fmt.Errorf("ledger replay item %s:%s:%d is not in the history replay", rr.Repo, it.Path, it.Line)
			}
			iFirst += b2i(im[0])
			iAny += b2i(im[1])
		}
	}
	got["ledger_replay.scored"] = strconv.Itoa(scored)
	got["ledger_replay.first_causing"] = fmt.Sprintf("%d/%d", first, scored)
	got["ledger_replay.any_causing"] = fmt.Sprintf("%d/%d", anyc, scored)
	got["impact_on_ledger_items.first_causing"] = fmt.Sprintf("%d/%d", iFirst, scored)
	got["impact_on_ledger_items.any_causing"] = fmt.Sprintf("%d/%d", iAny, scored)
	observeScoped(got, &lr)
	return nil
}

// observeScoped scores the same replay with quote scopes (ledger/v1 1.1): re-judgements and
// recall when a change outside a claim's scope carries its verdict forward.
func observeScoped(got map[string]string, lr *ledgerReplay) {
	var scored, first, anyc int
	for _, rr := range lr.Repos {
		stale, zero, carried := 0, 0, 0
		for _, c := range rr.Commits {
			stale += c.StaleScoped
			zero += b2i(c.StaleScoped == 0)
			for _, n := range c.Carried {
				carried += n
			}
		}
		got["ledger_replay.scoped."+rr.Repo+".stale_total"] = strconv.Itoa(stale)
		got["ledger_replay.scoped."+rr.Repo+".commits_staling_nothing"] = strconv.Itoa(zero)
		got["ledger_replay.scoped."+rr.Repo+".carried_quotes"] = strconv.Itoa(carried)
		for _, it := range rr.Items {
			if it.Status == "scored" {
				scored++
				first += b2i(it.FirstScoped)
				anyc += b2i(it.AnyScoped)
			}
		}
	}
	got["ledger_replay.scoped.first_causing"] = fmt.Sprintf("%d/%d", first, scored)
	got["ledger_replay.scoped.any_causing"] = fmt.Sprintf("%d/%d", anyc, scored)
}

// observeReplay reads the history replay per split.
func observeReplay(got map[string]string, file string) error {
	var rp replayJSON
	if err := readJSON(file, &rp); err != nil {
		return fmt.Errorf("history replay: %w", err)
	}
	type tally struct{ items, scored, first, anyc int }
	by := map[string]*tally{}
	for _, r := range rp.Repos {
		t := by[r.Split]
		if t == nil {
			t = &tally{}
			by[r.Split] = t
		}
		for _, it := range r.Items {
			t.items++
			if it.Status != "scored" {
				continue
			}
			t.scored++
			t.first += b2i(it.First)
			t.anyc += b2i(it.Any)
		}
	}
	for split, t := range by {
		got["history_replay."+split+".items"] = strconv.Itoa(t.items)
		got["history_replay."+split+".first_causing"] = fmt.Sprintf("%d/%d", t.first, t.scored)
		got["history_replay."+split+".any_causing"] = fmt.Sprintf("%d/%d", t.anyc, t.scored)
	}
	return nil
}

func observeFile(got map[string]string, name, file string) error {
	if file == "" {
		return fmt.Errorf("%s: an input file is missing", name)
	}
	sum, err := fileSHA256(file)
	if err != nil {
		return fmt.Errorf("%s: %w", name, err)
	}
	b, err := os.ReadFile(filepath.Clean(file))
	if err != nil {
		return fmt.Errorf("%s: %w", name, err)
	}
	got[name+".sha256"] = sum
	got[name+".lines"] = strconv.Itoa(strings.Count(string(b), "\n"))
	return nil
}

func observeMutations(got map[string]string, file string) error {
	if err := observeFile(got, "mutations", file); err != nil {
		return err
	}
	b, err := os.ReadFile(filepath.Clean(file))
	if err != nil {
		return fmt.Errorf("mutations: %w", err)
	}
	n, aff, uniq, err := mutationStats(b)
	if err != nil {
		return err
	}
	delete(got, "mutations.lines")
	got["mutations.count"] = strconv.Itoa(n)
	got["mutations.affected_lines"] = strconv.Itoa(aff)
	got["mutations.unique_affected_lines"] = strconv.Itoa(uniq)
	return nil
}
