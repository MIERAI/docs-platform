func testRepo(t *testing.T, files ...string) *repo.Repo {
	t.Helper()
	dir := t.TempDir()
	for _, f := range files {
		p := filepath.Join(dir, f)
		if err := os.MkdirAll(filepath.Dir(p), 0o750); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte("x"), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	r, err := repo.Open(dir, nil)
	if err != nil {
		t.Fatal(err)
	}
	return r
}

func sym(k model.Kind, name, prog string) model.Symbol {
	return model.Symbol{Kind: k, Name: name, Program: prog, Path: "src", Public: true, Confidence: model.ConfHigh}
}

func ref(k model.Kind, text, prog string, c model.Confidence) model.Reference {
	return model.Reference{Kind: k, Text: text, Program: prog, Path: "README.md", Line: 3, Confidence: c, Context: "code_span"}
}

func TestResolve(t *testing.T) {
	r := testRepo(t, "README.md", "scripts/run.sh", "docs/guide.md", "Makefile", "infra/modules/net/main.tf")
	inv := &scan.Inventory{CodeTokens: map[string]bool{"LEGACY_FLAG": true, "out/gen.json": true}}
	inv.Symbols = []model.Symbol{
		sym(model.KindProgram, "tool", ""), sym(model.KindCLIFlag, "--verbose", "tool"), sym(model.KindCLICommand, "check", "tool"),
		sym(model.KindEnvVar, "TOOL_TOKEN", ""), sym(model.KindMetric, "tool_requests_total", ""),
		sym(model.KindProgram, "make", ""), sym(model.KindMakeTarget, "build", "make"),
		sym(model.KindAnchor, "docs/guide.md#install", ""), sym(model.KindConfigKey, "image.tag", ""),
	}
	ix := newIndex(inv, r, []string{"dist/"})
	cases := []struct {
		name     string
		r        model.Reference
		want     Status
		wantConf model.Confidence
	}{
		{"flag ok", ref(model.KindCLIFlag, "--verbose", "tool", model.ConfMedium), Resolved, model.ConfMedium},
		{"flag missing", ref(model.KindCLIFlag, "--verbos", "tool", model.ConfMedium), Unresolved, model.ConfMedium},
		{"other tool's flag", ref(model.KindCLIFlag, "--context", "kubectl", model.ConfMedium), External, model.ConfMedium},
		{"bare flag, near miss", ref(model.KindCLIFlag, "--verbse", "", model.ConfMedium), Unresolved, model.ConfMedium},
		{"bare flag, unrelated", ref(model.KindCLIFlag, "--check", "", model.ConfMedium), Unresolved, model.ConfLow},
		{"command missing", ref(model.KindCLICommand, "chek", "tool", model.ConfMedium), Unresolved, model.ConfMedium},
		{"env ok via code token", ref(model.KindEnvVar, "LEGACY_FLAG", "", model.ConfMedium), Resolved, model.ConfMedium},
		{"env missing", ref(model.KindEnvVar, "TOOL_OLD", "", model.ConfMedium), Unresolved, model.ConfMedium},
		{"ambient env", ref(model.KindEnvVar, "HOME", "", model.ConfHigh), External, model.ConfHigh},
		{"metric family suffix", ref(model.KindMetric, "tool_requests", "", model.ConfMedium), Resolved, model.ConfMedium},
		{"metric in our namespace", ref(model.KindMetric, "tool_errors_total", "", model.ConfLow), Unresolved, model.ConfMedium},
		{"exporter metric", ref(model.KindMetric, "node_cpu_seconds_total", "", model.ConfMedium), External, model.ConfMedium},
		{"make target", ref(model.KindMakeTarget, "deploy", "make", model.ConfHigh), Unresolved, model.ConfHigh},
		{"path ok", ref(model.KindFilePath, "scripts/run.sh", "", model.ConfMedium), Resolved, model.ConfMedium},
		{"path with line", ref(model.KindFilePath, "scripts/run.sh:12", "", model.ConfMedium), Resolved, model.ConfMedium},
		{"path under existing dir", ref(model.KindFilePath, "scripts/gone.sh", "", model.ConfMedium), Unresolved, model.ConfHigh},
		{"path unknown top dir", ref(model.KindFilePath, "other/tool.sh", "", model.ConfMedium), Unresolved, model.ConfLow},
		{"path relative to subdir", ref(model.KindFilePath, "modules/net/main.tf", "", model.ConfMedium), Resolved, model.ConfMedium},
		{"gitignored output", ref(model.KindFilePath, "dist/app.tar", "", model.ConfMedium), Resolved, model.ConfMedium},
		{"generated by code", ref(model.KindFilePath, "out/gen.json", "", model.ConfMedium), Resolved, model.ConfMedium},
		{"placeholder", ref(model.KindFilePath, "design/x/Y.yaml", "", model.ConfMedium), External, model.ConfMedium},
		{"home path", ref(model.KindFilePath, "~/notes.md", "", model.ConfMedium), Outside, model.ConfLow},
		{"link ok", ref(model.KindLink, "docs/guide.md#install", "", model.ConfHigh), Resolved, model.ConfHigh},
		{"link bad anchor", ref(model.KindLink, "docs/guide.md#nope", "", model.ConfHigh), Unresolved, model.ConfMedium},
		{"link missing", ref(model.KindLink, "docs/none.md", "", model.ConfHigh), Unresolved, model.ConfHigh},
		{"link outside", ref(model.KindLink, "../other/README.md", "", model.ConfHigh), Outside, model.ConfMedium},
		{"config suffix", ref(model.KindConfigKey, "tag", "", model.ConfLow), Resolved, model.ConfLow},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			st, conf := ix.resolve(c.r)
			if st != c.want || (st != Resolved && conf != c.wantConf) {
				t.Errorf("resolve = %s/%s, want %s/%s", st, conf, c.want, c.wantConf)
			}
		})
	}
}

func TestRunAggregatesIgnoresAndReverse(t *testing.T) {
	r := testRepo(t, "README.md")
	inv := &scan.Inventory{CodeTokens: map[string]bool{}}
	inv.Symbols = []model.Symbol{
		sym(model.KindEnvVar, "DOCUMENTED", ""), sym(model.KindEnvVar, "SECRET_KNOB", ""),
		sym(model.KindEnvVar, "INTERNAL_X", ""),
		{Kind: model.KindCLIFlag, Name: "--hidden", Program: "helper", Public: true, Confidence: model.ConfHigh},
	}
	inv.References = []model.Reference{
		ref(model.KindEnvVar, "GONE_VAR", "", model.ConfMedium),
		{Kind: model.KindEnvVar, Text: "GONE_VAR", Path: "README.md", Line: 9, Confidence: model.ConfMedium},
		{Kind: model.KindEnvVar, Text: "SUPPRESSED", Path: "README.md", Line: 5, Confidence: model.ConfHigh},
	}
	inv.Mentions = []model.Mention{{Token: "$DOCUMENTED", InCode: true}}
	inv.Suppressions = []model.Suppression{{Path: "README.md", Line: 5, Reason: "r"}}
	rep := Run(inv, r, Options{
		MinConfidence: model.ConfMedium,
		Ignore:        []config.IgnoreRule{{Kind: "env_var", Text: "INTERNAL_*", Reason: "internal"}},
	})
	got := map[string]int{}
	for _, is := range rep.Issues {
		got[is.Type+" "+is.Subject] = len(is.Locations)
	}
	want := map[string]int{TypeWrong + " GONE_VAR": 2, TypeUndocumented + " SECRET_KNOB": 1}
	if len(got) != len(want) {
		t.Fatalf("issues = %v, want %v", got, want)
	}
	for k, n := range want {
		if got[k] != n {
			t.Errorf("issue %q: %d locations, want %d (all %v)", k, got[k], n, got)
		}
	}
}

func TestLevenshtein(t *testing.T) {
	cases := []struct {
		a, b string
		want int
	}{{"verbose", "verbos", 1}, {"color", "colour", 1}, {"abc", "abc", 0}, {"a", "abcdefgh", 4}}
	for _, c := range cases {
		if got := levenshtein(c.a, c.b, 4); got != c.want {
			t.Errorf("levenshtein(%q,%q) = %d, want %d", c.a, c.b, got, c.want)
		}
	}
}
