// Package group runs the continuous-consistency loop over a repository group
// (docs/design.md §12.4): documentation in one repository judged against code in others, at
// the revisions each doc set declares; one drift scan per code repository and commit,
// shared by every doc set; generated documents judged at their generator input; submodules
// and external sources never count as evidence.
package group

import (
	"context"
	"errors"
	"fmt"
	"regexp"
	"sort"
	"strings"

	"github.com/MIERAI/docs-platform/internal/agentic"
	"github.com/MIERAI/docs-platform/internal/instance"
	"github.com/MIERAI/docs-platform/internal/judge"
	"github.com/MIERAI/docs-platform/internal/ledger"
	"github.com/MIERAI/docs-platform/internal/repo"
)

// Checkouts maps "repo" or "repo@ref" to a checkout directory. docsp never changes a
// checkout: a target is served by "repo@ref", or by "repo" when its HEAD is that revision.
type Checkouts map[string]string

// Plan is a resolved group: what each doc set documents, where, and the drift scans needed.
type Plan struct {
	Group      string              `json:"group"`
	DocSets    []DocSetPlan        `json:"doc_sets"`
	DriftScans []TargetPlan        `json:"drift_scans"`
	External   []string            `json:"external,omitempty"`
	Submodules map[string][]string `json:"submodules,omitempty"`
	Problems   []string            `json:"problems,omitempty"`
}

// DocSetPlan is one doc set resolved against the checkouts.
type DocSetPlan struct {
	Name      string         `json:"name"`
	Repo      string         `json:"repo"`
	Dir       string         `json:"dir,omitempty"`
	Docs      []string       `json:"docs"`
	Generated []GeneratedDoc `json:"generated,omitempty"`
	Targets   []TargetPlan   `json:"targets"`
}

// GeneratedDoc is a generated document and its input ("" = unknown).
type GeneratedDoc struct {
	Path  string `json:"path"`
	Input string `json:"input,omitempty"`
	Why   string `json:"why"`
}

// TargetPlan is a target resolved to a commit and a checkout at that commit.
type TargetPlan struct {
	Repo   string `json:"repo"`
	Ref    string `json:"ref"`
	Commit string `json:"commit,omitempty"`
	Dir    string `json:"dir,omitempty"`
}

var reGenerated = regexp.MustCompile(`(?i)code generated .*do not edit|@generated|\bauto-?generated\b|\bgenerated by\b|\bdo not edit\b`)

// Resolve resolves a group against checkouts.
func Resolve(ctx context.Context, g instance.Group, co Checkouts) *Plan {
	p := &Plan{Group: g.Name, External: g.External, Submodules: map[string][]string{}}
	scans := map[string]TargetPlan{}
	for _, r := range g.Repos {
		if d := dirOf(co, g, r.Name); d != "" {
			if subs := submodules(ctx, d); len(subs) > 0 {
				p.Submodules[r.Name] = subs
			}
		}
	}
	for _, ds := range g.DocSets {
		dp := DocSetPlan{Name: ds.Name, Repo: ds.Repo, Dir: dirOf(co, g, ds.Repo)}
		if dp.Dir == "" {
			p.Problems = append(p.Problems, fmt.Sprintf("doc set %s: no checkout of %s (pass -checkout %s=DIR)", ds.Name, ds.Repo, ds.Repo))
			p.DocSets = append(p.DocSets, dp)
			continue
		}
		dp.Docs, dp.Generated = docsOf(ctx, dp.Dir, ds)
		targets := ds.Targets
		if len(targets) == 0 {
			targets = []instance.Target{{Repo: ds.Repo, Ref: "HEAD"}}
		}
		for _, t := range targets {
			tp, err := resolveTarget(ctx, g, co, t)
			if err != nil {
				p.Problems = append(p.Problems, fmt.Sprintf("doc set %s: %v", ds.Name, err))
			} else {
				scans[tp.Repo+"@"+tp.Commit] = tp
			}
			dp.Targets = append(dp.Targets, tp)
		}
		p.DocSets = append(p.DocSets, dp)
	}
	for _, k := range sortedKeys(scans) {
		p.DriftScans = append(p.DriftScans, scans[k])
	}
	return p
}

func dirOf(co Checkouts, g instance.Group, name string) string {
	if d := co[name]; d != "" {
		return d
	}
	for _, r := range g.Repos {
		if r.Name == name {
			return r.Path
		}
	}
	return ""
}

// resolveTarget finds a checkout at the target's revision.
func resolveTarget(ctx context.Context, g instance.Group, co Checkouts, t instance.Target) (TargetPlan, error) {
	tp := TargetPlan{Repo: t.Repo, Ref: t.Ref}
	for _, d := range []string{co[t.Repo+"@"+t.Ref], dirOf(co, g, t.Repo)} {
		if d == "" {
			continue
		}
		want, err := ledger.Resolve(ctx, d, t.Ref)
		if err != nil {
			continue
		}
		head, err := ledger.Resolve(ctx, d, "HEAD")
		if err == nil && head == want {
			tp.Commit, tp.Dir = want, d
			return tp, nil
		}
		tp.Commit = want
	}
	if tp.Commit == "" {
		return tp, fmt.Errorf("target %s@%s: no checkout knows that revision (pass -checkout %s@%s=DIR)", t.Repo, t.Ref, t.Repo, t.Ref)
	}
	return tp, fmt.Errorf("target %s@%s (%.12s): no checkout is at that revision; docsp never changes a checkout - pass -checkout %s@%s=DIR of a worktree at it",
		t.Repo, t.Ref, tp.Commit, t.Repo, t.Ref)
}

// docsOf lists the doc set's documents (tracked files matching its globs) and which are
// generated (configured, or marked in their first lines).
func docsOf(ctx context.Context, dir string, ds instance.DocSet) ([]string, []GeneratedDoc) {
	out, err := repo.Git(ctx, dir, "ls-files", "-z", "--", ".")
	if err != nil {
		return nil, nil
	}
	var docs []string
	var gen []GeneratedDoc
	for _, f := range strings.Split(out, "\x00") {
		if f == "" || !repo.MatchAny(ds.Docs, f) {
			continue
		}
		if g, ok := generatedBy(ctx, dir, ds, f); ok {
			gen = append(gen, g)
			continue
		}
		docs = append(docs, f)
	}
	return docs, gen
}

func generatedBy(ctx context.Context, dir string, ds instance.DocSet, f string) (GeneratedDoc, bool) {
	for _, g := range ds.Generated {
		if repo.Match(g.Docs, f) {
			return GeneratedDoc{Path: f, Input: g.Input, Why: "configured as generated"}, true
		}
	}
	text, ok := ledger.FileAt(ctx, dir, "HEAD", f)
	if !ok {
		return GeneratedDoc{}, false
	}
	head := strings.SplitN(text, "\n", 6)
	if reGenerated.MatchString(strings.Join(head[:min(5, len(head))], "\n")) {
		return GeneratedDoc{Path: f, Why: "generated marker in its first lines"}, true
	}
	return GeneratedDoc{}, false
}

// submodules lists the submodule paths of a checkout (git links in its tree).
func submodules(ctx context.Context, dir string) []string {
	out, err := repo.Git(ctx, dir, "ls-tree", "-r", "-z", "HEAD")
	if err != nil {
		return nil
	}
	var subs []string
	for _, rec := range strings.Split(out, "\x00") {
		meta, p, ok := strings.Cut(rec, "\t")
		if f := strings.Fields(meta); ok && len(f) == 3 && f[1] == "commit" {
			subs = append(subs, p)
		}
	}
	return subs
}

// external are the globs of non-evidence paths in one target repository: the group's
// external globs and the repository's submodules.
func (p *Plan) external(repoName string) []string {
	out := append([]string{}, p.External...)
	for _, s := range p.Submodules[repoName] {
		out = append(out, s+"/")
	}
	return out
}

// Line is a documentation line to judge.
type Line struct {
	Path string
	Line int
}

// JudgeOptions configure judging a doc set.
type JudgeOptions struct {
	Guard    *judge.Guard
	Instance *instance.Instance
	CacheDir string
	Ledger   *ledger.Ledger
}

// Judged reports one doc set's judging against one target.
type Judged struct {
	Target  TargetPlan           `json:"target"`
	Results []agentic.LineResult `json:"results"`
	Claims  int                  `json:"claims"`
}

// Judge judges lines of a doc set against each of its targets: one runner (and one drift
// scan) per target commit, shared across doc sets through the runners map; claims go into
// the ledger with their target.
func Judge(ctx context.Context, p *Plan, docSet string, lines []Line, o JudgeOptions, runners map[string]*agentic.Runner) ([]Judged, error) {
	dp, err := p.docSet(docSet)
	if err != nil {
		return nil, err
	}
	var out []Judged
	for _, t := range dp.Targets {
		if t.Dir == "" {
			return nil, fmt.Errorf("doc set %s: target %s@%s has no checkout at its revision", docSet, t.Repo, t.Ref)
		}
		run := p.runner(dp, t, o, runners)
		j := Judged{Target: t}
		byDoc := map[string][]int{}
		for _, l := range lines {
			byDoc[l.Path] = append(byDoc[l.Path], l.Line)
		}
		for _, d := range sortedKeys(byDoc) {
			j.Results = append(j.Results, run.Judge(ctx, d, byDoc[d])...)
		}
		if o.Ledger != nil {
			n, err := record(ctx, dp, t, run, o, j.Results)
			if err != nil {
				return nil, err
			}
			j.Claims = n
		}
		out = append(out, j)
	}
	return out, nil
}

func (p *Plan) docSet(name string) (DocSetPlan, error) {
	for _, d := range p.DocSets {
		if d.Name == name {
			if d.Dir == "" {
				return d, fmt.Errorf("doc set %s: no checkout of %s", name, d.Repo)
			}
			return d, nil
		}
	}
	return DocSetPlan{}, fmt.Errorf("no doc set %q in group %s", name, p.Group)
}

// runner returns the shared runner of a target commit, configured for this doc set's
// documents.
func (p *Plan) runner(dp DocSetPlan, t TargetPlan, o JudgeOptions, runners map[string]*agentic.Runner) *agentic.Runner {
	key := t.Repo + "@" + t.Commit + "\x00" + dp.Repo + "\x00" + dp.Dir
	if r, ok := runners[key]; ok {
		return r
	}
	gen := map[string]string{}
	for _, g := range dp.Generated {
		gen[g.Path] = g.Input
	}
	r := agentic.New(agentic.Options{
		Guard: o.Guard, Repo: t.Repo, Dir: t.Dir, Class: o.Instance.Classification, CacheDir: o.CacheDir,
		Settings: agentic.FromInstance(o.Instance.AI.Judge.Agentic), DocDir: dp.Dir, DocRepo: dp.Repo, External: p.external(t.Repo),
		Generated: func(f string) (string, bool) { in, ok := gen[f]; return in, ok },
	})
	runners[key] = r
	return r
}

// record merges the judged lines into the ledger as claims against the target.
func record(ctx context.Context, dp DocSetPlan, t TargetPlan, run *agentic.Runner, o JudgeOptions, rs []agentic.LineResult) (int, error) {
	b, err := ledger.NewTargetBuilder(ctx, dp.Dir, dp.Repo, "HEAD", t.Dir, ledger.Target{Repo: t.Repo, Ref: t.Ref}, t.Commit)
	if err != nil {
		return 0, err //nolint:wrapcheck // already descriptive
	}
	b.Class, b.Model = o.Instance.Classification, o.Guard.Name()
	if d, err := run.Drift(ctx); err == nil {
		b.Drift = d
	}
	n := 0
	for i := range rs {
		if c, ok := b.Claim(ctx, &rs[i]); ok {
			o.Ledger.Merge(c)
			n++
		}
	}
	return n, nil
}

// ErrNoGroup: the instance configuration has no group of that name.
var ErrNoGroup = errors.New("no such group in the instance configuration")

// Find returns the named group.
func Find(in *instance.Instance, name string) (instance.Group, error) {
	for _, g := range in.Groups {
		if g.Name == name || name == "" && len(in.Groups) == 1 {
			return g, nil
		}
	}
	return instance.Group{}, fmt.Errorf("%w: %q", ErrNoGroup, name)
}

// Dirs maps the group's checkouts for CheckGroup: "repo" for document repositories and
// "repo@ref" for each declared target's checkout at its revision.
func (p *Plan) Dirs() map[string]string {
	out := map[string]string{}
	for _, d := range p.DocSets {
		if d.Dir != "" {
			out[d.Repo] = d.Dir
		}
		for _, t := range d.Targets {
			if t.Dir != "" {
				out[t.Repo+"@"+t.Ref] = t.Dir
			}
		}
	}
	return out
}

func sortedKeys[V any](m map[string]V) []string {
	ks := make([]string, 0, len(m))
	for k := range m {
		ks = append(ks, k)
	}
	sort.Strings(ks)
	return ks
}
