func git(t *testing.T, dir string, args ...string) string {
	t.Helper()
	out, err := exec.Command("git", append([]string{"-C", dir, "-c", "user.name=t", "-c", "user.email=t@e", "-c", "init.defaultBranch=main"}, args...)...).CombinedOutput()
	if err != nil {
		t.Fatalf("git %v: %v %s", args, err, out)
	}
	return strings.TrimSpace(string(out))
}

func write(t *testing.T, dir string, files map[string]string) {
	t.Helper()
	for p, c := range files {
		full := filepath.Join(dir, p)
		if err := os.MkdirAll(filepath.Dir(full), 0o750); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(full, []byte(c), 0o600); err != nil {
			t.Fatal(err)
		}
	}
}

// setup: code repository "api" (prod = first commit: port 8080; develop = second: port
// 9090, plus a vendored copy) and docs repository "docs" (design docs describe develop,
// runbooks describe prod, one generated reference page).
func setup(t *testing.T) (instance.Group, Checkouts, string, string) {
	t.Helper()
	root := t.TempDir()
	api, docs, prod := filepath.Join(root, "api"), filepath.Join(root, "docs"), filepath.Join(root, "api-prod")
	for _, d := range []string{api, docs} {
		if err := os.MkdirAll(d, 0o750); err != nil {
			t.Fatal(err)
		}
		git(t, d, "init", "-q")
	}
	write(t, api, map[string]string{"config.yaml": "port: 8080\n"})
	git(t, api, "add", "-A")
	git(t, api, "commit", "-qm", "v1")
	git(t, api, "branch", "prod")
	write(t, api, map[string]string{"config.yaml": "port: 9090\n", "vendor/lib/config.yaml": "port: 1234\n"})
	git(t, api, "add", "-A")
	git(t, api, "commit", "-qm", "v2")
	git(t, api, "branch", "develop")
	if out, err := exec.Command("git", "clone", "-q", "-b", "prod", api, prod).CombinedOutput(); err != nil {
		t.Fatalf("%v %s", err, out)
	}
	write(t, docs, map[string]string{
		"design/api.md":    "# API\n\nThe API listens on port 9090.\n",
		"runbooks/api.md":  "# Runbook\n\nThe API listens on port 8080.\n",
		"reference/cli.md": "<!-- Code generated by gen-cli. DO NOT EDIT. -->\n# CLI\n",
	})
	git(t, docs, "add", "-A")
	git(t, docs, "commit", "-qm", "docs")
	g := instance.Group{
		Name: "shop", Repos: []instance.GroupRepo{{Name: "api", Role: instance.RoleCode}, {Name: "docs", Role: instance.RoleDocs}},
		DocSets: []instance.DocSet{
			{Name: "design", Repo: "docs", Docs: []string{"design/**", "reference/**"}, Targets: []instance.Target{{Repo: "api", Ref: "develop"}}},
			{Name: "runbooks", Repo: "docs", Docs: []string{"runbooks/**"}, Targets: []instance.Target{{Repo: "api", Ref: "prod"}}},
		},
		External: []string{"vendor/"},
	}
	return g, Checkouts{"api": api, "docs": docs, "api@prod": prod}, api, docs
}

func TestResolvePlan(t *testing.T) {
	g, co, api, _ := setup(t)
	p := Resolve(context.Background(), g, co)
	if len(p.Problems) != 0 || len(p.DriftScans) != 2 {
		t.Fatalf("plan %+v", p)
	}
	d := p.DocSets[0]
	if d.Docs[0] != "design/api.md" || len(d.Generated) != 1 || d.Generated[0].Path != "reference/cli.md" || d.Targets[0].Dir != api {
		t.Fatalf("design %+v", d)
	}
	if r := p.DocSets[1]; r.Targets[0].Dir != co["api@prod"] || r.Targets[0].Commit != git(t, api, "rev-parse", "prod") {
		t.Fatalf("runbooks %+v", r)
	}
	// without a checkout at prod, the plan says so instead of reading the wrong revision
	delete(co, "api@prod")
	p = Resolve(context.Background(), g, co)
	if len(p.Problems) != 1 || !strings.Contains(p.Problems[0], "never changes a checkout") {
		t.Fatalf("problems %v", p.Problems)
	}
}

// portAgent answers every line from the code repository it explores: it reads config.yaml
// through the tools and quotes it (contradicted when the doc's port differs), and also
// quotes the vendored copy (external: must not count).
type portAgent struct{}

func (portAgent) Name() string    { return "agent" }
func (portAgent) Model() string   { return "m" }
func (portAgent) Cloud() bool     { return false }
func (portAgent) Billing() string { return judgev1.BillingNone }
func (portAgent) Close() error    { return nil }
func (portAgent) Modes() []string { return []string{judgev1.ModeAgentic} }
func (portAgent) Judge(ctx context.Context, r *judgev1.Request) (*judgev1.Response, error) {
	var a any = map[string]any{"drift": []any{}}
	if r.Task.Type == judgev1.TaskClaimFacts {
		res := judge.ToolsFrom(ctx).Call(ctx, judgev1.ToolCall{Tool: judgev1.ToolReadFile, Args: json.RawMessage(`{"path":"config.yaml"}`)})
		line := strings.TrimSpace(strings.SplitN(res.Text, "\n", 3)[1][3:])
		status := agentic.Confirmed
		if !strings.Contains(r.Claim.Text, strings.TrimPrefix(line, "port: ")) {
			status = agentic.Contradicted
		}
		a = map[string]any{"facts": []any{map[string]any{"fact": "port", "status": status, "evidence": []any{
			map[string]any{"kind": "quote", "path": "config.yaml", "line": 1, "quote": line},
			map[string]any{"kind": "quote", "path": "vendor/lib/config.yaml", "line": 1, "quote": "port: 1234"},
		}}}, "reason": "r"}
	}
	b, _ := json.Marshal(a)
	return judgev1.NewStructuredResponse(r, b, judgev1.ParseSchema, judgev1.Model{Provider: "agent", ID: "m"}, judgev1.Usage{}), nil
}

func TestJudgeAcrossRepositoriesAndInvalidate(t *testing.T) {
	g, co, api, docs := setup(t)
	ctx := context.Background()
	in := &instance.Instance{Version: 1, Classification: instance.Classification{Default: instance.Public}}
	gd, err := judge.NewGuard("judge", portAgent{}, in)
	if err != nil {
		t.Fatal(err)
	}
	p := Resolve(ctx, g, co)
	l := &ledger.Ledger{SchemaVersion: ledger.SchemaVersion}
	runners := map[string]*agentic.Runner{}
	o := JudgeOptions{Guard: gd, Instance: in, Ledger: l}
	jd, err := Judge(ctx, p, "design", []Line{{"design/api.md", 3}, {"reference/cli.md", 2}}, o, runners)
	if err != nil {
		t.Fatal(err)
	}
	jr, err := Judge(ctx, p, "runbooks", []Line{{"runbooks/api.md", 3}}, o, runners)
	if err != nil {
		t.Fatal(err)
	}
	if jd[0].Results[0].Category != agentic.Confirmed || jr[0].Results[0].Category != agentic.Confirmed {
		t.Fatalf("design %+v\nrunbook %+v", jd[0].Results, jr[0].Results)
	}
	if gen := jd[0].Results[1]; !gen.Generated || !strings.Contains(gen.Error, "generator input") {
		t.Fatalf("generated doc judged: %+v", gen)
	}
	if ev := jd[0].Results[0].Facts[0].Evidence; !ev[0].OK || ev[1].OK || !strings.Contains(ev[1].Reason, "external") {
		t.Fatalf("evidence %+v", ev)
	}
	if len(l.Claims) != 2 || len(runners) != 2 {
		t.Fatalf("claims %d runners %d", len(l.Claims), len(runners))
	}
	for _, c := range l.Claims {
		if c.Target == nil || c.Target.Repo != "api" || c.Evidence.Quotes[0].Repo != "api" || c.DocRef != git(t, docs, "rev-parse", "HEAD") || len(c.Evidence.Quotes) != 1 {
			t.Fatalf("claim %+v", c)
		}
	}
	// develop moves on: only the design claim (documenting develop) is stale
	write(t, api, map[string]string{"config.yaml": "port: 7070\n"})
	git(t, api, "commit", "-qam", "v3")
	git(t, api, "branch", "-f", "develop")
	r, err := ledger.CheckGroup(ctx, l, "shop", p.Dirs(), time.Now())
	if err != nil {
		t.Fatal(err)
	}
	st := map[string]string{}
	for _, c := range r.Claims {
		st[c.Path] = c.Status
	}
	if st["design/api.md"] != ledger.Stale || st["runbooks/api.md"] != ledger.Fresh {
		t.Fatalf("statuses %v %+v", st, r.Claims)
	}
	// a docs edit of the runbook line stales it too
	write(t, docs, map[string]string{"runbooks/api.md": "# Runbook\n\nThe API listens on port 8081.\n"})
	git(t, docs, "commit", "-qam", "edit")
	r, _ = ledger.CheckGroup(ctx, l, "shop", p.Dirs(), time.Now())
	for _, c := range r.Claims {
		if c.Path == "runbooks/api.md" && (c.Status != ledger.Stale || c.Reasons[0].Kind != ledger.ReasonDocLineChanged) {
			t.Fatalf("runbook %+v", c)
		}
	}
}
