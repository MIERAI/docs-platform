const sqlWrapped = `-- Code generated. DO NOT EDIT.

-- name: ListWidgets :many
SELECT t2.code, t2.label, t2.price
FROM (
    SELECT t1.code AS code, t1.label AS label, t1.price::float8 AS price /* cast */
    FROM widgets AS t1
    WHERE (t1.shop_id = sqlc.arg(shop_id)::int8)
      AND ((sqlc.narg(min_price)::numeric IS NULL) OR (t1.price >= sqlc.narg(min_price)::numeric))
      AND (t1.code = ANY(sqlc.arg(codes)::text[]))
      AND (t1.state = 3::int4)
      AND (t1.created_at < (sqlc.arg(factory_now)::timestamptz - make_interval(days => sqlc.arg(age_days)::int4)))
) AS t2
WHERE (sqlc.narg(cursor_code)::text IS NULL OR (t2.code COLLATE "C") > (sqlc.narg(cursor_code)::text))
ORDER BY t2.code COLLATE "C", t2.price DESC
LIMIT 51;
`

func TestParseSQLQuery(t *testing.T) {
	q := parseSQLQuery(sqlWrapped, factoryMachinery)
	if q.Name != "ListWidgets" || q.Cmd != ":many" {
		t.Errorf("name %q %q", q.Name, q.Cmd)
	}
	wantParams := map[string]sqlParam{
		"shop_id": {Type: "int8"}, "min_price": {Type: "numeric", Optional: true},
		"codes": {Type: "text[]"}, "age_days": {Type: "int4"},
	}
	if !reflect.DeepEqual(q.Params, wantParams) {
		t.Errorf("params %+v", q.Params)
	}
	wantOut := []sqlOutput{{Name: "code", Column: "code"}, {Name: "label", Column: "label"}, {Name: "price", Column: "price", Cast: "float8"}}
	if !reflect.DeepEqual(q.Outputs, wantOut) {
		t.Errorf("outputs %+v", q.Outputs)
	}
	if !reflect.DeepEqual(q.Tables, []string{"widgets"}) {
		t.Errorf("tables %v", q.Tables)
	}
	wantF := []sqlCmp{{Column: "shop_id", Op: "eq", Params: []string{"shop_id"}}, {Column: "price", Op: "gte", Params: []string{"min_price"}}, {Column: "code", Op: "in", Params: []string{"codes"}}}
	if !reflect.DeepEqual(q.Filters, wantF) {
		t.Errorf("filters %+v", q.Filters)
	}
	if !reflect.DeepEqual(q.Derived, []sqlCmp{{Column: "created_at", Op: "lt", Params: []string{"age_days"}}}) {
		t.Errorf("derived %+v", q.Derived)
	}
	if !reflect.DeepEqual(q.Fixed, []sqlCmp{{Column: "state", Op: "eq", Value: "3"}}) {
		t.Errorf("fixed %+v", q.Fixed)
	}
	if !reflect.DeepEqual(q.Order, []string{"code asc", "price desc"}) || q.Limit != "51" {
		t.Errorf("order %v limit %q", q.Order, q.Limit)
	}
}

func TestParseSQLJoinsAndLiterals(t *testing.T) {
	src := `-- name: GetBox :one
SELECT b.id, b.owner_id, i.qty, (t.data ->> 'colour')::text AS colour, count(*) AS n
FROM boxes b
LEFT JOIN items i ON i.box_id = b.id
JOIN tags AS t ON t.box_id = b.id
WHERE b.id = @box_id AND b.min_qty <> b.max_qty AND b.note LIKE 'it''s%'
GROUP BY b.id;`
	q := parseSQLQuery(src, nil)
	if !reflect.DeepEqual(q.Tables, []string{"boxes", "items", "tags"}) {
		t.Errorf("tables %v", q.Tables)
	}
	names := []string{}
	for _, o := range q.Outputs {
		names = append(names, o.Name+"="+o.Column)
	}
	if strings.Join(names, ",") != "id=id,owner_id=owner_id,qty=qty,colour=colour,n=" {
		t.Errorf("outputs %v", names)
	}
	if _, ok := q.Params["box_id"]; !ok || len(q.Filters) != 1 || q.Filters[0].Column != "id" {
		t.Errorf("params %v filters %+v", q.Params, q.Filters)
	}
	wantFixed := []sqlCmp{{Column: "min_qty", Op: "ne", Value: "max_qty"}, {Column: "note", Op: "prefix", Value: "it's%"}}
	if !reflect.DeepEqual(q.Fixed, wantFixed) {
		t.Errorf("fixed %+v", q.Fixed)
	}
}

// TestSQLEquivalentFormsAgree: comments, whitespace and a reordered SELECT / AND list give
// the same contract.
func TestSQLEquivalentFormsAgree(t *testing.T) {
	a := "-- name: Q :one\nSELECT t1.a AS a, t1.b AS b FROM t AS t1 WHERE (t1.a = sqlc.arg(a)::int4) AND (t1.c = 2::int4);"
	b := "-- name: Q :one\n-- a comment\nSELECT t1.b AS b,\n       t1.a AS a\nFROM t AS t1\nWHERE  ( t1.c = 2::int4 )\n  AND  ( t1.a =   sqlc.arg(a)::int4 ) ;"
	sa, sb := surfaceOf(a), surfaceOf(b)
	if !reflect.DeepEqual(sa, sb) {
		t.Errorf("equivalent queries differ:\n%+v\n%+v", sa, sb)
	}
}

func surfaceOf(src string) Operation {
	op := Operation{Name: "Q"}
	applySQL(&op, parseSQLQuery(src, factoryMachinery), tableTypes{"t": {"a": "int32", "b": "text"}}, "")
	s := Surface{Operations: []Operation{op}}
	s.Normalize()
	return s.Operations[0]
}

func TestParseSchema(t *testing.T) {
	tt := tableTypes{}
	parseSchema(`-- shop
CREATE TABLE IF NOT EXISTS public.widgets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    label VARCHAR(40) NOT NULL,
    price NUMERIC(10, 2) CHECK (price >= 0),
    tags TEXT[] NOT NULL DEFAULT '{}',
    seen_at TIMESTAMP WITH TIME ZONE,
    ratio DOUBLE PRECISION,
    CONSTRAINT widgets_label_uq UNIQUE (label)
);`, tt)
	want := map[string]string{"id": "int64", "label": "text", "price": "decimal", "tags": "list<text>", "seen_at": "timestamp", "ratio": "float"}
	if !reflect.DeepEqual(tt["widgets"], want) {
		t.Errorf("schema %+v", tt)
	}
}

func FuzzParseSQLQuery(f *testing.F) {
	f.Add(sqlWrapped)
	f.Add("-- name: X :one\nSELECT ((((a")
	f.Add("SELECT * FROM (SELECT 1) AS x WHERE (y = ANY(sqlc.arg(z)::int4[])) ORDER BY")
	f.Add(")))) AS ,,, sqlc.narg( :: ")
	f.Fuzz(func(t *testing.T, s string) {
		q := parseSQLQuery(s, factoryMachinery)
		for _, c := range append(append(q.Filters, q.Derived...), q.Fixed...) {
			if c.Column == "" {
				t.Fatalf("comparison without a column: %+v", c)
			}
		}
	})
}

