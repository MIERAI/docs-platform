func libraryDiff(t *testing.T, override map[string]string) []Item {
	t.Helper()
	dir := t.TempDir()
	for p, c := range libraryProject {
		if o, ok := override[p]; ok {
			c = o
		}
		writeFile(t, dir, p, c)
	}
	ctx := context.Background()
	design, err := OpenSource(ctx, "lib", dir, "", []string{"design/**", "specs/**", "db/schema/**"})
	if err != nil {
		t.Fatal(err)
	}
	code, err := OpenSource(ctx, "lib", dir, "", []string{"db/**", "internal/handler/**"})
	if err != nil {
		t.Fatal(err)
	}
	doc, err := Run(ctx, Options{DesignAdapter: "factory-design", CodeAdapter: "factory-code", Design: design, Code: code})
	if err != nil {
		t.Fatal(err)
	}
	if doc.Summary.DesignOperations != 4 || doc.Summary.CodeOperations != 4 || doc.Summary.Overlap != 4 {
		t.Fatalf("summary %+v", doc.Summary)
	}
	return doc.Items
}

func itemKeys(items []Item, minSev string) []string {
	rank := map[string]int{SevInfo: 0, SevLow: 1, SevMedium: 2, SevHigh: 3}
	var out []string
	for _, it := range items {
		if rank[it.Severity] >= rank[minSev] {
			out = append(out, it.Operation+" "+it.Kind+" "+it.Subject)
		}
	}
	sort.Strings(out)
	return out
}

func TestFactoryConsistent(t *testing.T) {
	items := libraryDiff(t, nil)
	if got := itemKeys(items, SevLow); len(got) != 0 {
		t.Errorf("a consistent project reports %v", got)
	}
	// the compute function does not read the input it may read: informational only
	if got := itemKeys(items, SevInfo); strings.Join(got, ";") != "GetShelfStats rule.missing_in_code rules.reads_input.shelf" {
		t.Errorf("info items %v", got)
	}
}

func TestFactoryDrifts(t *testing.T) {
	for _, tc := range []struct {
		name, file, old, new string
		want                 []string
	}{
		{
			"param renamed", "db/queries/library.get-book.sql", "sqlc.arg(isbn)", "sqlc.arg(code)",
			[]string{"GetBook input.missing_in_code inputs.isbn", "GetBook input.missing_in_design inputs.code"},
		},
		{
			"output source", "db/queries/library.get-book.sql", "t1.shelf AS shelf_no", "t1.state AS shelf_no",
			[]string{"GetBook output.column outputs.shelf_no"},
		},
		{
			"fixed condition", "db/queries/library.list-lent.sql", "(t1.state = 2::int4)", "(t1.state = 1::int4)",
			[]string{"ListLent rule.missing_in_code rules.fixed.state", "ListLent rule.missing_in_design rules.fixed.state"},
		},
		{
			"limit", "db/queries/library.list-lent.sql", "LIMIT 51", "LIMIT 100",
			[]string{"ListLent rule.changed rules.limit.rows"},
		},
		{
			"derived filter", "db/queries/library.list-lent.sql", "t1.lent_at <", "t1.lent_at >",
			[]string{"ListLent rule.missing_in_code rules.filter.lent_at", "ListLent rule.missing_in_design rules.filter.lent_at"},
		},
		{
			"compute signature", "internal/handler/library/get_shelf_stats_logic.go", "rows []getShelfStatsRow)", "rows []getShelfStatsRow, n int)",
			[]string{"GetShelfStats rule.changed rules.signature.getShelfStatsLogic"},
		},
		{
			"compute output", "internal/handler/library/get_shelf_stats_logic.go", "res.Lent++", "res.Borrowed++",
			[]string{"GetShelfStats output.missing_in_code outputs.lent", "GetShelfStats output.missing_in_design outputs.borrowed"},
		},
		{
			"compute column via helper", "internal/handler/library/get_shelf_stats_logic.go", "r.Isbn", "r.Title",
			[]string{"GetShelfStats rule.missing_in_design rules.reads.title"},
		},
		{
			"hand SQL column", "db/queries/library.find-author.sql", "SELECT a.id, a.name", "SELECT a.id",
			[]string{"FindAuthor rule.missing_in_code rules.selects.name"},
		},
	} {
		t.Run(tc.name, func(t *testing.T) {
			c := libraryProject[tc.file]
			if strings.Count(c, tc.old) != 1 {
				t.Fatalf("snippet %q", tc.old)
			}
			got := itemKeys(libraryDiff(t, map[string]string{tc.file: strings.Replace(c, tc.old, tc.new, 1)}), SevLow)
			if strings.Join(got, ";") != strings.Join(tc.want, ";") {
				t.Errorf("got  %v\nwant %v", got, tc.want)
			}
		})
	}
}

