// Set is a named collection of names the code defines, used to check enumerations.
type Set struct {
	Name  string          `json:"name"`
	Path  string          `json:"path"` // where the set lives (evidence location)
	Line  int             `json:"line,omitempty"`
	Items map[string]bool `json:"-"`
}

// Index is the evidence index of one repository.
type Index struct {
	Repo  *repo.Repo
	Facts []Fact
	Sets  []Set
	// Symbols are the layer-③ symbols by exact name.
	Symbols map[string][]model.Symbol
	// Generated holds code files that carry a "generated, do not edit" marker.
	Generated map[string]bool
	// CommentedCron holds files with a commented-out cron line (a disabled schedule).
	CommentedCron map[string][]Fact
	// DocFiles are the documentation files (never evidence).
	DocFiles map[string]bool
	byWord   map[string][]int
	byItem   map[string][]int
	content  map[string][]string
	// tokenFiles maps a lowercase identifier-like token to the code files containing it.
	tokenFiles map[string][]string
}

var (
	reGenerated = regexp.MustCompile(`(?i)code generated .{0,80}do not edit|@generated|\bDO NOT EDIT\b|auto-?generated|generated by `)
	reCronLine  = regexp.MustCompile(`^\s*#\s*-?\s*cron:\s*['"]?([^'"#]+)`)
)

// Build indexes the repository: every non-documentation file is read once (bounded by
// repo.MaxFileSize), nothing is executed.
func Build(r *repo.Repo, inv *scan.Inventory) *Index {
	ix := &Index{
		Repo: r, Symbols: map[string][]model.Symbol{}, Generated: map[string]bool{},
		CommentedCron: map[string][]Fact{}, DocFiles: map[string]bool{}, byWord: map[string][]int{},
		byItem: map[string][]int{}, content: map[string][]string{}, tokenFiles: map[string][]string{},
	}
	for _, d := range inv.DocFiles {
		ix.DocFiles[d] = true
	}
	for _, s := range inv.Symbols {
		ix.Symbols[s.Name] = append(ix.Symbols[s.Name], s)
	}
	yamlDocs := map[string][]yamlkeys.Doc{}
	for _, f := range inv.CodeFiles {
		ix.readCode(f, yamlDocs)
	}
	ix.buildSets(inv, yamlDocs)
	for i, f := range ix.Facts {
		for _, w := range Words(f.Leaf) {
			ix.byWord[w] = append(ix.byWord[w], i)
		}
	}
	return ix
}

func (ix *Index) readCode(f string, yamlDocs map[string][]yamlkeys.Doc) {
	b, err := ix.Repo.Read(f)
	if err != nil {
		return
	}
	ls := lines(b)
	ix.content[f] = ls
	seen := map[string]bool{}
	for _, t := range reFileToken.FindAllString(strings.ToLower(string(b)), -1) {
		if !seen[t] {
			seen[t] = true
			ix.tokenFiles[t] = append(ix.tokenFiles[t], f)
		}
	}
	head := strings.Join(ls[:min(len(ls), 6)], "\n")
	if reGenerated.MatchString(head) {
		ix.Generated[f] = true
	}
	facts, docs := factsOf(f, b)
	ix.Facts = append(ix.Facts, facts...)
	if docs != nil {
		yamlDocs[f] = docs
		for i, l := range ls {
			if m := reCronLine.FindStringSubmatch(l); m != nil {
				fc := newFact(f, i+1, "cron", m[1])
				fc.Commented = true
				ix.CommentedCron[f] = append(ix.CommentedCron[f], fc)
			}
		}
	}
}

var reFileToken = regexp.MustCompile(`[a-z_][a-z0-9_]{3,40}`)

// maxTokenFiles: a token in more files than this is too common to locate anything.
const maxTokenFiles = 12

// Search ranks code files by the rare tokens they share with the query tokens (IDF-weighted).
// A file needs at least two distinct rare tokens, or one token found in a single file.
func (ix *Index) Search(tokens []string, limit int) []string {
	score := map[string]float64{}
	hits := map[string]int{}
	seen := map[string]bool{}
	for _, t := range tokens {
		t = strings.ToLower(t)
		fs := ix.tokenFiles[t]
		if seen[t] || len(fs) == 0 || len(fs) > maxTokenFiles {
			continue
		}
		seen[t] = true
		w := 1 / float64(len(fs))
		for _, f := range fs {
			score[f] += w
			hits[f]++
		}
	}
	var out []string
	for f, sc := range score {
		if hits[f] >= 2 || sc >= 1 {
			out = append(out, f)
		}
	}
	sort.Slice(out, func(i, j int) bool {
		if score[out[i]] != score[out[j]] {
			return score[out[i]] > score[out[j]]
		}
		return out[i] < out[j]
	})
	return out[:min(limit, len(out))]
}

// Lines returns the content of an indexed code file (nil for unknown files).
func (ix *Index) Lines(p string) []string { return ix.content[p] }

func (ix *Index) addSet(s Set) {
	if len(s.Items) < 2 || len(s.Items) > 60 {
		return
	}
	ix.Sets = append(ix.Sets, s)
	for it := range s.Items {
		ix.byItem[it] = append(ix.byItem[it], len(ix.Sets)-1)
	}
}

func (ix *Index) buildSets(inv *scan.Inventory, yamlDocs map[string][]yamlkeys.Doc) {
	ix.dirSets()
	ix.symbolSets(inv)
	files := make([]string, 0, len(yamlDocs))
	for f := range yamlDocs {
		files = append(files, f)
	}
	sort.Strings(files)
	for _, f := range files {
		ix.yamlChildSets(f, yamlDocs[f])
	}
	ix.valueSets()
}

// dirSets: the children of every directory (names without extension).
func (ix *Index) dirSets() {
	children := map[string]map[string]bool{}
	add := func(dir, name string) {
		if children[dir] == nil {
			children[dir] = map[string]bool{}
		}
		children[dir][claim.NormItem(name)] = true
	}
	for _, f := range ix.Repo.AllFiles() {
		dir, base := path.Split(f)
		add(strings.TrimSuffix(dir, "/"), strings.TrimSuffix(base, path.Ext(base)))
		for d := strings.TrimSuffix(dir, "/"); d != ""; {
			parent, name := path.Split(d)
			add(strings.TrimSuffix(parent, "/"), name)
			d = strings.TrimSuffix(parent, "/")
		}
	}
	for dir, items := range children {
		if dir == "" {
			dir = "."
		}
		ix.addSet(Set{Name: "children of " + dir + "/", Path: dir, Items: items})
	}
}

func (ix *Index) symbolSets(inv *scan.Inventory) {
	groups := map[string]*Set{}
	for _, s := range inv.Symbols {
		var key string
		switch s.Kind {
		case model.KindCLICommand:
			key = "commands of " + s.Program
		case model.KindMakeTarget:
			key = "make targets"
		case model.KindEnvVar, model.KindCLIFlag, model.KindMetric:
			key = string(s.Kind) + " in " + s.Path
		default:
			continue
		}
		g := groups[key]
		if g == nil {
			g = &Set{Name: key, Path: s.Path, Line: s.Line, Items: map[string]bool{}}
			groups[key] = g
		}
		g.Items[claim.NormItem(s.Name)] = true
	}
	for _, k := range sortedKeys(groups) {
		ix.addSet(*groups[k])
	}
}

// yamlChildSets: the child keys of every mapping (jobs of a workflow, apps of a values file).
func (ix *Index) yamlChildSets(f string, docs []yamlkeys.Doc) {
	groups := map[string]*Set{}
	for _, d := range docs {
		for _, k := range d.Keys {
			parent := strings.TrimSuffix(strings.TrimSuffix(k.Path, k.Leaf), ".")
			g := groups[parent]
			if g == nil {
				g = &Set{Name: "keys of " + f + ":" + parent, Path: f, Line: k.Line, Items: map[string]bool{}}
				groups[parent] = g
			}
			g.Items[claim.NormItem(k.Leaf)] = true
		}
	}
	for _, k := range sortedKeys(groups) {
		ix.addSet(*groups[k])
	}
}

// valueSets: the distinct values of one key across the repository (namespaces, clusters).
func (ix *Index) valueSets() {
	groups := map[string]*Set{}
	for _, f := range ix.Facts {
		if f.IsNum || len(f.Value) > 60 || strings.ContainsAny(f.Value, " /:{}$") || f.Value == "" {
			continue
		}
		g := groups[f.Leaf]
		if g == nil {
			g = &Set{Name: "values of " + f.Leaf, Path: f.Path, Line: f.Line, Items: map[string]bool{}}
			groups[f.Leaf] = g
		}
		g.Items[claim.NormItem(f.Value)] = true
	}
	for _, k := range sortedKeys(groups) {
		ix.addSet(*groups[k])
	}
}

// GeneratedSet is the set of entries directly under dir (or the root for ".") whose code files
// are mostly marked generated: what a "these paths are generated" list should enumerate.
func (ix *Index) GeneratedSet(dir string, codeFiles []string) Set {
	prefix := ""
	if dir != "." && dir != "" {
		prefix = dir + "/"
	}
	total, gen := map[string]int{}, map[string]int{}
	for _, f := range codeFiles {
		rel, ok := strings.CutPrefix(f, prefix)
		if !ok {
			continue
		}
		top, _, _ := strings.Cut(rel, "/")
		total[top]++
		if ix.Generated[f] {
			gen[top]++
		}
	}
	s := Set{Name: "generated paths under " + dir + "/", Path: dir, Items: map[string]bool{}}
	for top, n := range total {
		if gen[top] > 0 && 2*gen[top] >= n {
			s.Items[claim.NormItem(strings.TrimSuffix(top, path.Ext(top)))] = true
		}
	}
	return s
}

// SetsWith returns the indexes of sets containing item.
func (ix *Index) SetsWith(item string) []int { return ix.byItem[item] }

// FactsWithWord returns facts whose leaf key contains the word.
func (ix *Index) FactsWithWord(w string) []Fact {
	var out []Fact
	for _, i := range ix.byWord[strings.ToLower(w)] {
		out = append(out, ix.Facts[i])
	}
	return out
}

// FactsNamed returns facts whose leaf or full key equals name (case-insensitive), or whose
// key ends with ".name".
func (ix *Index) FactsNamed(name string) []Fact {
	n := strings.ToLower(strings.Trim(name, "`$ "))
	if n == "" {
		return nil
	}
	var out []Fact
	for _, f := range ix.Facts {
		k := strings.ToLower(f.Key)
		if strings.ToLower(f.Leaf) == n || k == n || strings.HasSuffix(k, "."+n) {
			out = append(out, f)
		}
	}
	return out
}

func sortedKeys[V any](m map[string]V) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}

// Words splits an identifier (camelCase, snake_case, kebab-case, dotted) into lowercase words.
func Words(s string) []string {
	var out []string
	for _, part := range strings.FieldsFunc(s, func(r rune) bool { return strings.ContainsRune("_-./ :", r) }) {
		out = append(out, camel(part)...)
	}
	return out
}

func camel(s string) []string {
	var out []string
	start := 0
	rs := []rune(s)
	for i := 1; i < len(rs); i++ {
		lowerToUpper := unicode.IsLower(rs[i-1]) && unicode.IsUpper(rs[i])
		acronymEnd := i+1 < len(rs) && unicode.IsUpper(rs[i-1]) && unicode.IsUpper(rs[i]) && unicode.IsLower(rs[i+1])
		digit := unicode.IsDigit(rs[i-1]) != unicode.IsDigit(rs[i])
		if lowerToUpper || acronymEnd || digit {
			out = append(out, strings.ToLower(string(rs[start:i])))
			start = i
		}
	}
	return append(out, strings.ToLower(string(rs[start:])))
}
