func TestFactsOf(t *testing.T) {
	cases := []struct {
		path, src, key, value string
		kind                  claim.ValueKind
	}{
		{"values.yaml", "prometheus:\n  retention: 30d\n", "prometheus.retention", "30d", claim.Duration},
		{"wf.yml", "on:\n  schedule:\n    - cron: '0 0 * * *'\n", "on.schedule.cron", "0 0 * * *", claim.Cron},
		{"main.go", "const notifyTimeout = 5 * time.Second\n", "notifyTimeout", "5 * time.Second", claim.Duration},
		{"main.go", "\tfs.Duration(\"timeout\", 30*time.Second, \"t\")\n", "timeout", "30*time.Second", ""},
		{"main.tf", "  retention_in_days = 14\n", "retention_in_days", "14", ""},
		{"run.sh", "KEEP=${KEEP_DAYS:-7}\n", "KEEP_DAYS", "7", ""},
		{"Dockerfile", "FROM golang:1.27.4-alpine AS build\n", "golang", "1.27.4-alpine", claim.Version},
		{"app.yaml", "spec:\n  source:\n    chart: kube-prometheus-stack\n    targetRevision: 65.1.0\n", "kube-prometheus-stack", "65.1.0", claim.Version},
	}
	for _, c := range cases {
		t.Run(c.path+" "+c.key, func(t *testing.T) {
			facts, _ := factsOf(c.path, []byte(c.src))
			for _, f := range facts {
				if f.Key != c.key {
					continue
				}
				if f.Value != c.value {
					t.Errorf("value %q, want %q", f.Value, c.value)
				}
				if c.kind != "" && !slices.ContainsFunc(f.Vals, func(v claim.Value) bool { return v.Kind == c.kind }) {
					t.Errorf("no %s value in %+v", c.kind, f.Vals)
				}
				return
			}
			t.Fatalf("no fact %q in %+v", c.key, facts)
		})
	}
}

func TestWords(t *testing.T) {
	cases := map[string][]string{
		"retentionInDays":   {"retention", "in", "days"},
		"RETENTION_DAYS":    {"retention", "days"},
		"HTTPServerTimeout": {"http", "server", "timeout"},
		"spec.max-age":      {"spec", "max", "age"},
	}
	for in, want := range cases {
		if got := Words(in); !slices.Equal(got, want) {
			t.Errorf("Words(%q) = %v, want %v", in, got, want)
		}
	}
}

func TestBuild(t *testing.T) {
	dir := t.TempDir()
	files := map[string]string{
		"apps/alpha/values.yaml":        "replicas: 2\n",
		"apps/beta/values.yaml":         "replicas: 3\n",
		"gen/a.go":                      "// Code generated by x. DO NOT EDIT.\npackage gen\n",
		".github/workflows/nightly.yml": "on:\n  workflow_dispatch: {}\n#  schedule:\n#    - cron: '0 3 * * *'\n",
		".github/workflows/weekly.yml":  "on:\n  schedule:\n    - cron: '0 3 * * 1'\njobs:\n  a: {}\n  b: {}\n",
		"README.md":                     "docs\n",
	}
	for p, c := range files {
		full := filepath.Join(dir, p)
		if err := os.MkdirAll(filepath.Dir(full), 0o750); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(full, []byte(c), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	r, err := repo.Open(dir, nil)
	if err != nil {
		t.Fatal(err)
	}
	inv := &scan.Inventory{DocFiles: []string{"README.md"}}
	for _, f := range r.Files() {
		if f != "README.md" {
			inv.CodeFiles = append(inv.CodeFiles, f)
		}
	}
	ix := Build(r, inv)
	if !ix.Generated["gen/a.go"] || ix.Generated["apps/alpha/values.yaml"] {
		t.Errorf("generated markers: %v", ix.Generated)
	}
	if len(ix.CommentedCron[".github/workflows/nightly.yml"]) != 1 {
		t.Errorf("commented cron not found: %v", ix.CommentedCron)
	}
	found := false
	for _, si := range ix.SetsWith("alpha") {
		found = found || ix.Sets[si].Items["beta"]
	}
	if !found {
		t.Error("children of apps/ should be a set")
	}
	if g := ix.GeneratedSet(".", inv.CodeFiles); !g.Items["gen"] || g.Items["apps"] {
		t.Errorf("generated set %v", g.Items)
	}
	if len(ix.FactsNamed("replicas")) != 2 || len(ix.FactsWithWord("replicas")) != 2 {
		t.Error("facts by name/word")
	}
}

func FuzzFactsOf(f *testing.F) {
	f.Add("x.yaml", []byte("a:\n  b: 30d\n  image: repo/x:1.2.3\n"))
	f.Add("x.go", []byte("const A = 5 * time.Second\nfs.Int(\"n\", 4, \"\")\n"))
	f.Add("x.tf", []byte("a = \"b\"\n# c = 3\n"))
	f.Add("Dockerfile", []byte("FROM --platform=x a/b:c\n"))
	f.Fuzz(func(t *testing.T, p string, b []byte) {
		facts, _ := factsOf(p, b)
		for _, x := range facts {
			if x.Path != p {
				t.Fatalf("fact path %q", x.Path)
			}
		}
	})
}
